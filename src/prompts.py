"""提示词的唯一真源与版本号。

为什么要单独一个模块
--------------------
提示词原先散落在旧编排层（`src/graph.py`，2026-10-20 已删）各节点的 f-string 里。
这种写法的代价不是"不好看"，而是三个具体的能力缺失：

  1. **无法回答"线上跑的是哪一版"**。提示词是模型行为的一部分，但改动它不留任何
     版本痕迹 —— 线上答得不好时，无法判断是不是提示词被改过，也无法把质量变化
     关联到具体改动；
  2. **无法单独回滚**。提示词与代码烧在同一个镜像里，回滚提示词只能回滚整个服务
     （连带把不相关的改动一起退回）；
  3. **无法做灰度和 A/B**。同一份代码只能跑一套提示词。

把提示词集中到这里、并配一个显式的 `PROMPT_VERSION`，前两项立刻成立：版本号会
随每次生成一起写进日志与 SSE 的 `done` 事件，于是"这条回答由哪版提示词产生"
成了可核对的事实；回滚提示词也退化为回滚这一个模块。

改提示词的规程
--------------
改任何一个模板文本，**必须同时 bump `PROMPT_VERSION`**。
`tests/test_prompts.py` 里存着「版本号 → 全部模板文本的指纹」的映射表，
只改文本不改版本号会直接测红。这条约束是刻意的：它逼作者意识到"这是一次
会影响模型行为的变更"，而不是顺手改个措辞。

为什么不在这里放 system 角色消息
--------------------------------
本项目的提示词都是"单条 user 消息"形态（首轮问答 / 对照评测）。agent 链路的
instructions 不在这里 —— 那是 `Agent` 原语自带的字段，见 `src/agents/*.py`。
模板保持与调用点同构，避免引入一层与调用方不对应的抽象。

⚠️ 2026-10-20 删掉了 `revise_prompt` / `evaluate_prompt`：它们只服务旧的
修订节点与评分节点，两个节点随图一起删了，删完这两个模板**没有任何生产调用点**
（只有测试在调）。agent 链路的评审走 `src/agents/evaluator.py` 自己的 instructions，
不走这里。
"""

from __future__ import annotations

#: 提示词版本。**任何模板文本变更都必须同步 bump 本常量**（见模块 docstring）。
#: 版本号随每次生成进入日志与 SSE `done` 事件，是"线上跑的是哪一版"的唯一答案。
PROMPT_VERSION = "1.0.0"


def answer_prompt(context: str, question: str) -> str:
    """首轮作答模板：带 RAG 上下文。

    context: **已经过 `guard.wrap_context` 处理**的上下文（含结构边界与抗注入声明）。
        调用方负责这层防护 —— 提示词模块不感知安全策略，只负责措辞。
    question: 用户需求原文（最后一条用户消息）。

    注意不要把"资料里可能夹带指令"的免责声明写在这里：那是 `RAG_GUARD` 开关的
    职责，写在模板里会让"关掉 guard"这个动作失效。
    """
    return f"参考以下资料作答：\n{context}\n\n用户需求：{question}"
